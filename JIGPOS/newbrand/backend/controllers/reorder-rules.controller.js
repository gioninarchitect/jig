// Reorder Rules Controller — Business logic extracted from routes/reorder-rules.js
const ReorderRule = require('../modules/database/models/ReorderRule');
const Product = require('../modules/database/models/Product');
const BranchInventory = require('../modules/database/models/BranchInventory');
const PurchaseOrder = require('../modules/database/models/PurchaseOrder');

// GET / — List reorder rules with optional filters
async function getAll(req, res) {
  try {
    const { branch, isActive, autoOrderEnabled } = req.query;
    const query = {};
    if (branch) query.branch = branch;
    if (isActive !== undefined) query.isActive = isActive === 'true';
    if (autoOrderEnabled !== undefined) query.autoOrderEnabled = autoOrderEnabled === 'true';

    const rules = await ReorderRule.find(query)
      .populate('product', 'name sku category inventory')
      .populate('branch', 'name')
      .populate('preferredSupplier', 'name')
      .sort('-createdAt');

    res.json({ success: true, rules: rules, data: rules });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
}

// GET /:id — Get single reorder rule
async function getById(req, res) {
  try {
    const rule = await ReorderRule.findById(req.params.id)
      .populate('product', 'name sku category inventory')
      .populate('branch', 'name')
      .populate('preferredSupplier', 'name');

    if (!rule) {
      return res.status(404).json({ success: false, message: 'Reorder rule not found' });
    }

    res.json({ success: true, rule: rule, data: rule });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
}

// GET /check — Check stock levels and return items needing reorder
async function check(req, res) {
  try {
    const { branch } = req.query;

    const rules = await ReorderRule.find({ isActive: true, ...(branch && { branch }) })
      .populate('product', 'name sku category inventory')
      .populate('branch', 'name')
      .populate('preferredSupplier', 'name contactEmail');

    const needsReorder = [];

    for (const rule of rules) {
      let currentStock = 0;

      if (rule.branch) {
        // Check branch-specific inventory
        const branchInv = await BranchInventory.findOne({
          product: rule.product._id,
          branch: rule.branch
        });
        currentStock = branchInv?.quantity || 0;
      } else {
        // Check global product inventory
        currentStock = rule.product?.inventory?.quantity || 0;
      }

      if (currentStock <= rule.reorderPoint) {
        needsReorder.push({
          rule,
          currentStock,
          deficit: rule.reorderPoint - currentStock,
          suggestedOrder: rule.reorderQuantity
        });
      }
    }

    res.json({ success: true, data: needsReorder, count: needsReorder.length });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
}

// POST /:id/trigger — Trigger auto-reorder, creates PurchaseOrder
async function trigger(req, res) {
  try {
    const rule = await ReorderRule.findById(req.params.id)
      .populate('product', 'name sku costPrice')
      .populate('preferredSupplier', 'name');

    if (!rule) {
      return res.status(404).json({ success: false, message: 'Reorder rule not found' });
    }

    // Create purchase order
    const po = new PurchaseOrder({
      supplier: rule.preferredSupplier,
      branch: rule.branch,
      items: [{
        product: rule.product._id,
        name: rule.product.name,
        sku: rule.product.sku,
        quantity: rule.reorderQuantity,
        unitPrice: rule.lastOrderPrice || rule.product.costPrice || 0,
        total: rule.reorderQuantity * (rule.lastOrderPrice || rule.product.costPrice || 0)
      }],
      status: rule.requiresApproval ? 'pending' : 'approved',
      autoGenerated: true,
      reorderRule: rule._id,
      createdBy: req.user.id,
      expectedDelivery: new Date(Date.now() + rule.leadTimeDays * 24 * 60 * 60 * 1000)
    });

    await po.save();

    // Update rule
    rule.lastTriggered = new Date();
    rule.lastOrderId = po._id;
    await rule.save();

    res.json({ success: true, data: { rule, purchaseOrder: po } });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
}

// POST / — Create reorder rule
async function create(req, res) {
  try {
    const rule = new ReorderRule({
      ...req.body,
      createdBy: req.user.id
    });
    await rule.save();
    res.status(201).json({ success: true, data: rule });
  } catch (error) {
    res.status(400).json({ success: false, message: error.message });
  }
}

// PUT /:id — Update reorder rule
async function update(req, res) {
  try {
    const rule = await ReorderRule.findByIdAndUpdate(
      req.params.id,
      req.body,
      { new: true, runValidators: true }
    );
    if (!rule) {
      return res.status(404).json({ success: false, message: 'Reorder rule not found' });
    }
    res.json({ success: true, data: rule });
  } catch (error) {
    res.status(400).json({ success: false, message: error.message });
  }
}

// DELETE /:id — Delete reorder rule (owner only)
async function remove(req, res) {
  try {
    const rule = await ReorderRule.findByIdAndDelete(req.params.id);
    if (!rule) {
      return res.status(404).json({ success: false, message: 'Reorder rule not found' });
    }
    res.json({ success: true, message: 'Reorder rule deleted' });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
}

module.exports = {
  getAll,
  getById,
  check,
  trigger,
  create,
  update,
  remove
};
